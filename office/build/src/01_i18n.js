function TR(k,v){const s=(uiLang()==="en"?I18N_EN:I18N_ZH)[k];const t=(s==null?I18N_ZH[k]:s)||k;
  return v?t.replace(/\{(\w+)\}/g,(m,n)=>(n in v)?String(v[n]):m):t}

/* 页面里带 data-t 的元素换成当前语言（正文、title）：换语言时重画一次 */
function applyTr(root){const r=root||document;
  r.querySelectorAll("[data-t]").forEach(el=>{el.textContent=TR(el.getAttribute("data-t"))});
  r.querySelectorAll("[data-t-title]").forEach(el=>{el.setAttribute("title",TR(el.getAttribute("data-t-title")))})}

